@Composable
fun Nice64Theme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) Nice64DarkColorScheme else Nice64LightColorScheme,
        typography = Nice64Typography,
        shapes = Nice64Shapes,
        content = content,
    )
}
