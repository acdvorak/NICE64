#ifndef JOYBUS_TRANSPORT_H
#define JOYBUS_TRANSPORT_H

#ifndef NICE_RX_BACKEND_PIO
#define NICE_RX_BACKEND_PIO 0
#endif

#ifndef NICE_TX_BACKEND_BITBANG
#define NICE_TX_BACKEND_BITBANG 0
#endif

typedef enum {
    JOYBUS_RX_BACKEND_GPIO_BITBANG = 0,
    JOYBUS_RX_BACKEND_PIO = 1,
} joybus_rx_backend_t;

typedef enum {
    JOYBUS_TX_BACKEND_PIO = 0,
    JOYBUS_TX_BACKEND_CPU_BITBANG = 1,
} joybus_tx_backend_t;

#define JOYBUS_ACTIVE_RX_BACKEND \
    (NICE_RX_BACKEND_PIO ? JOYBUS_RX_BACKEND_PIO : JOYBUS_RX_BACKEND_GPIO_BITBANG)

#define JOYBUS_ACTIVE_TX_BACKEND \
    (NICE_TX_BACKEND_BITBANG ? JOYBUS_TX_BACKEND_CPU_BITBANG : JOYBUS_TX_BACKEND_PIO)

#define JOYBUS_RX_BACKEND_IS_PIO (NICE_RX_BACKEND_PIO)
#define JOYBUS_TX_BACKEND_IS_CPU_BITBANG (NICE_TX_BACKEND_BITBANG)

#endif
